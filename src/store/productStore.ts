import { create } from 'zustand';
import { Product } from '@/types/types';

interface ProductStore {
  products: Product[];
  getProductsByCategory: (categoryIds: number[]) => Product[];
}

function generateProducts(
  categoryId: number,
  names: string[],
  basePrice: number,
  standard: string = 'GOST R 51685-2013',
  length: string = '12.5M / 25M',
  weight: string = '65.0 KG/M'
): Product[] {
  return names.map((name, idx) => {
    const isUsed = name.includes('Б/У');
    const price = isUsed ? Math.round(basePrice * 0.6) : basePrice;
    const available = !name.includes('Нет');

    return {
      id: `${categoryId}-${idx}`.toString(),
      name: name.split(' - ')[0] || name,
      subtitle: isUsed ? 'Б/У' : 'Новый',
      standard,
      length,
      weight,
      price: price.toString(),
      priceUnit: 'RUB',
      status: available ? ('IN STOCK' as const) : ('OUT OF STOCK' as const),
      type: 'rail' as const,
      image: '/products/1.png',
      categoryId: categoryId,
    };
  });
}

